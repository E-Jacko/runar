#!/usr/bin/env node
// -----------------------------------------------------------------------------
// BN254 PAIRING VECTOR INVARIANT CHECK  (v1 audit — Go-only crypto oracle gap)
// -----------------------------------------------------------------------------
//
// `tests/vectors/bn254_pairing.json` is the oracle for the single most
// security-critical operation in the Groth16 path, and it has two problems the
// 2026-08 audit named:
//
//   1. BN254/Groth16 codegen ships in the Go tier ONLY, so "cross-tier parity"
//      is definitionally vacuous — one implementation cannot disagree with
//      itself. The vectors are the whole oracle.
//   2. The vectors are generated by gnark-crypto via tests/generate-vectors/bn254.
//      That is a genuine second implementation, but it is still ONE
//      implementation's output recorded, with no official upstream KAT behind it.
//
// This script adds the check that needs neither a second pairing nor an upstream
// KAT: it falsifies a wrong pairing using ALGEBRA over the recorded values.
//
//   (I1) BILINEARITY.  e(a*G1, b*G2) = e(G1, G2)^(a*b), so the result depends on
//        a*b mod r and on nothing else. Every vector tagged with the same
//        `group` key must therefore carry byte-identical `expected_gt`. The
//        corpus emits each product in several spellings (scalar on G1, scalar on
//        G2, and every non-trivial factorisation), so a pairing that is not
//        bilinear cannot produce a self-consistent file.
//   (I2) DEGENERACY.  `is_one: true` must mean expected_gt IS the Fp12 identity,
//        and `is_one: false` must mean it is not. This pins the pairings that
//        must collapse (point at infinity, and the Groth16 product whose
//        exponents cancel).
//   (I3) NON-DEGENERACY.  The corpus must contain negative controls — products
//        that must NOT be 1 — otherwise "return 1 for everything" satisfies
//        every positive vector.
//   (I4) CANONICITY.  Every field element is 64 lowercase hex chars and < p, and
//        every vector's point counts are consistent (2 limbs per G1 term, 4 per
//        G2 term, equal term counts).
//   (I5) COVERAGE FLOOR.  The corpus cannot be quietly emptied: minimum counts
//        for bilinearity classes, multi-member classes, identity vectors and
//        negative controls.
//
// An implementation error in the generator, or a hand-edit of the checked-in
// file, has to satisfy all five simultaneously to pass.
//
// Dependency-light by design: Node built-ins only. No npm install.
//
// Usage:
//   node conformance/scripts/check-bn254-pairing-invariants.mjs [--file <path>]
//   node conformance/scripts/check-bn254-pairing-invariants.mjs --self-test
//
// Exit code: 0 = all invariants hold; 1 = violation; 2 = usage/internal error.
// -----------------------------------------------------------------------------

import { readFileSync, existsSync } from 'node:fs';
import { resolve, join } from 'node:path';

// BN254 base field modulus (the `prime` the fp vector files record).
const P = 21888242871839275222246405745257275088696311157297823662689037894645226208583n;

// gnark-crypto's GT.Marshal() lays Fp12 out as 12 big-endian Fp limbs with the
// multiplicative identity in the LAST limb.
const GT_LIMBS = 12;
const GT_IDENTITY = Array.from({ length: GT_LIMBS }, (_, i) =>
  (i === GT_LIMBS - 1 ? 1n : 0n).toString(16).padStart(64, '0'),
);

const DEFAULT_REL = 'tests/vectors/bn254_pairing.json';

// Minimum shape the corpus must keep. These exist so that "delete the awkward
// vectors" is a failing change rather than a silent one.
const FLOOR = {
  vectors: 20,
  bilinearGroups: 4,
  multiMemberGroups: 4, // groups that actually constrain anything (>= 2 members)
  identityVectors: 4,   // is_one: true
  negativeControls: 4,  // is_one: false on a product_pairing
};

function isCanonicalFieldHex(s) {
  if (typeof s !== 'string' || !/^[0-9a-f]{64}$/.test(s)) return false;
  return BigInt('0x' + s) < P;
}

/**
 * Core check — pure over its input so the self-test can drive it directly.
 * @param {{ vectors: Array }} doc
 * @returns {{ violations: string[], stats: object }}
 */
export function checkInvariants(doc) {
  const violations = [];
  const v = (msg) => violations.push(msg);

  if (!doc || !Array.isArray(doc.vectors)) {
    return { violations: ['file has no "vectors" array'], stats: {} };
  }
  const vectors = doc.vectors;

  // ---- (I4) canonicity + shape ------------------------------------------
  vectors.forEach((vec, i) => {
    const at = `vector[${i}] (${vec.description ?? 'no description'})`;
    if (!Array.isArray(vec.expected_gt) || vec.expected_gt.length !== GT_LIMBS) {
      v(`${at}: expected_gt must be ${GT_LIMBS} limbs, got ${vec.expected_gt?.length}`);
    } else {
      vec.expected_gt.forEach((h, j) => {
        if (!isCanonicalFieldHex(h)) v(`${at}: expected_gt[${j}] is not a canonical 64-hex Fp element (< p)`);
      });
    }
    if (!Array.isArray(vec.g1_points) || vec.g1_points.length % 2 !== 0) {
      v(`${at}: g1_points must be 2 limbs per term`);
    }
    if (!Array.isArray(vec.g2_points) || vec.g2_points.length % 4 !== 0) {
      v(`${at}: g2_points must be 4 limbs per term`);
    }
    const g1Terms = (vec.g1_points?.length ?? 0) / 2;
    const g2Terms = (vec.g2_points?.length ?? 0) / 4;
    if (g1Terms !== g2Terms) {
      v(`${at}: ${g1Terms} G1 term(s) but ${g2Terms} G2 term(s) — a pairing product needs one of each`);
    }
    if (g1Terms === 0) v(`${at}: no pairing terms`);
    for (const [name, arr] of [['g1_points', vec.g1_points], ['g2_points', vec.g2_points]]) {
      if (!Array.isArray(arr)) continue;
      arr.forEach((h, j) => {
        // The point at infinity is encoded as all-zero limbs, which is canonical.
        if (!isCanonicalFieldHex(h)) v(`${at}: ${name}[${j}] is not a canonical 64-hex Fp element (< p)`);
      });
    }
    if (typeof vec.is_one !== 'boolean') v(`${at}: is_one must be a boolean`);
  });

  // ---- (I2) degeneracy: is_one agrees with the recorded GT ----------------
  const isIdentity = (gt) =>
    Array.isArray(gt) && gt.length === GT_LIMBS && gt.every((h, i) => h === GT_IDENTITY[i]);
  vectors.forEach((vec, i) => {
    const at = `vector[${i}] (${vec.description ?? 'no description'})`;
    const ident = isIdentity(vec.expected_gt);
    if (vec.is_one === true && !ident) {
      v(`${at}: is_one=true but expected_gt is NOT the Fp12 identity — a pairing that must collapse did not`);
    }
    if (vec.is_one === false && ident) {
      v(`${at}: is_one=false but expected_gt IS the Fp12 identity — a pairing that must not collapse did`);
    }
  });

  // ---- (I1) bilinearity: one expected_gt per group ------------------------
  const groups = new Map();
  for (const vec of vectors) {
    if (!vec.group) continue;
    if (!groups.has(vec.group)) groups.set(vec.group, []);
    groups.get(vec.group).push(vec);
  }
  for (const [key, members] of groups) {
    const distinct = new Set(members.map((m) => (m.expected_gt ?? []).join(',')));
    if (distinct.size > 1) {
      v(
        `bilinearity BROKEN for group "${key}": ${members.length} vectors that must share one ` +
          `pairing result carry ${distinct.size} distinct expected_gt values. e(a*G1, b*G2) ` +
          `depends only on a*b mod r, so this cannot happen for a correct pairing:\n` +
          members.map((m) => `      - ${m.description}`).join('\n'),
      );
    }
  }

  // ---- (I3)+(I5) coverage floor ------------------------------------------
  const multiMember = [...groups.values()].filter((m) => m.length >= 2).length;
  const identityVectors = vectors.filter((x) => x.is_one === true).length;
  const negativeControls = vectors.filter((x) => x.is_one === false && x.op === 'product_pairing').length;
  const stats = {
    vectors: vectors.length,
    bilinearGroups: groups.size,
    multiMemberGroups: multiMember,
    identityVectors,
    negativeControls,
  };
  for (const [k, min] of Object.entries(FLOOR)) {
    if (stats[k] < min) {
      v(`coverage floor: ${k} = ${stats[k]}, must be >= ${min} (the corpus may not be narrowed)`);
    }
  }

  return { violations, stats };
}

// --- self-test ---------------------------------------------------------------
function makeGT(last) {
  return Array.from({ length: GT_LIMBS }, (_, i) =>
    (i === GT_LIMBS - 1 ? BigInt(last) : 0n).toString(16).padStart(64, '0'),
  );
}
const ZERO = '0'.repeat(64);
function goodDoc() {
  const vectors = [];
  for (let g = 0; g < 5; g++) {
    for (let m = 0; m < 2; m++) {
      vectors.push({
        op: 'single_pairing',
        g1_points: [ZERO, ZERO],
        g2_points: [ZERO, ZERO, ZERO, ZERO],
        group: `bilinear:k=${g}`,
        expected_gt: makeGT(2 + g),
        is_one: false,
        description: `class ${g} member ${m}`,
      });
    }
  }
  for (let i = 0; i < 5; i++) {
    vectors.push({
      op: 'product_pairing',
      g1_points: [ZERO, ZERO, ZERO, ZERO],
      g2_points: [ZERO, ZERO, ZERO, ZERO, ZERO, ZERO, ZERO, ZERO],
      expected_gt: makeGT(1),
      is_one: true,
      description: `identity ${i}`,
    });
    vectors.push({
      op: 'product_pairing',
      g1_points: [ZERO, ZERO, ZERO, ZERO],
      g2_points: [ZERO, ZERO, ZERO, ZERO, ZERO, ZERO, ZERO, ZERO],
      expected_gt: makeGT(7 + i),
      is_one: false,
      description: `negative control ${i}`,
    });
  }
  return { field: 'bn254', vectors };
}

function selfTest() {
  const cases = [];
  const run = (name, mutate, expectFail) => {
    const doc = goodDoc();
    if (mutate) mutate(doc);
    const { violations } = checkInvariants(doc);
    const failed = violations.length > 0;
    cases.push({ name, ok: failed === expectFail, expected: expectFail ? 'REJECT' : 'PASS', got: failed ? 'REJECT' : 'PASS', first: violations[0]?.split('\n')[0] ?? '' });
  };

  run('a) a well-formed corpus', null, false);
  run('b) bilinearity broken (one class member disagrees)', (d) => {
    const m = d.vectors.find((x) => x.group === 'bilinear:k=1');
    m.expected_gt = makeGT(999);
  }, true);
  run('c) is_one=true but GT is not the identity', (d) => {
    d.vectors.find((x) => x.is_one === true).expected_gt = makeGT(5);
  }, true);
  run('d) is_one=false but GT IS the identity', (d) => {
    d.vectors.find((x) => x.is_one === false).expected_gt = makeGT(1);
  }, true);
  run('e) all negative controls deleted', (d) => {
    d.vectors = d.vectors.filter((x) => x.is_one !== false);
  }, true);
  run('f) non-canonical field element (>= p)', (d) => {
    d.vectors[0].expected_gt[0] = P.toString(16).padStart(64, '0');
  }, true);
  run('g) G1/G2 term counts disagree', (d) => {
    d.vectors[0].g1_points = [ZERO, ZERO, ZERO, ZERO];
  }, true);
  run('h) corpus narrowed below the floor', (d) => {
    d.vectors = d.vectors.slice(0, 6);
  }, true);

  console.log('BN254 pairing invariants — self-test (both directions):');
  console.log('');
  let allOk = true;
  for (const c of cases) {
    console.log(`  ${c.ok ? '✓' : '✗'}  ${c.name}`);
    console.log(`         expected=${c.expected}  got=${c.got}   (${c.first})`);
    if (!c.ok) allOk = false;
  }
  console.log('');
  console.log(allOk ? '✓ SELF-TEST PASSED' : '✗ SELF-TEST FAILED');
  return allOk ? 0 : 1;
}

// --- CLI ---------------------------------------------------------------------
function main() {
  const argv = process.argv.slice(2);
  let file = null;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--self-test') process.exit(selfTest());
    else if (argv[i] === '--file') file = resolve(argv[++i]);
    else {
      console.error(`Unknown argument: ${argv[i]}`);
      process.exit(2);
    }
  }
  if (!file) file = join(process.cwd(), DEFAULT_REL);
  if (!existsSync(file)) {
    console.error(`BN254 pairing invariants: file not found: ${file}`);
    process.exit(2);
  }

  let doc;
  try {
    doc = JSON.parse(readFileSync(file, 'utf8'));
  } catch (e) {
    console.error(`BN254 pairing invariants: ${file} is not valid JSON: ${e.message}`);
    process.exit(2);
  }

  const { violations, stats } = checkInvariants(doc);
  console.log(`BN254 pairing invariants — ${file}`);
  console.log(
    `  ${stats.vectors} vectors · ${stats.bilinearGroups} bilinearity class(es) ` +
      `(${stats.multiMemberGroups} with >= 2 members) · ${stats.identityVectors} identity ` +
      `· ${stats.negativeControls} negative control(s)`,
  );
  if (violations.length === 0) {
    console.log('✓ all invariants hold (bilinearity, degeneracy, non-degeneracy, canonicity, coverage floor)');
    process.exit(0);
  }
  console.error('');
  console.error(`✗ BN254 PAIRING INVARIANTS VIOLATED — ${violations.length} problem(s):`);
  console.error('');
  for (const x of violations) console.error(`  ✗ ${x}`);
  console.error('');
  console.error('These are algebraic facts about a bilinear pairing, checked over the recorded');
  console.error('values alone. A violation means the vectors cannot have come from a correct');
  console.error('pairing — regenerate with tests/generate-vectors/bn254 and investigate.');
  process.exit(1);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
